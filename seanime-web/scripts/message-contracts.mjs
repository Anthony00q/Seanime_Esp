import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { IntlMessageFormat } from "intl-messageformat"

const localeRoot = fileURLToPath(new URL("../src/locales/", import.meta.url))
export const normalizeContractSource = source => source.replace(/\r\n/g, "\n")
const argumentTypes = {
    number: ["number"], date: ["date", "number"], select: ["string", "boolean"], text: ["string", "number"], string: ["string"],
}

export function messageArguments(ast, output = new Map()) {
    for (const element of ast) {
        const kind = [2, 6].includes(element.type) ? "number" : [3, 4].includes(element.type) ? "date"
            : element.type === 5 ? "select" : element.type === 1 ? "text" : undefined
        if (kind) {
            const previous = output.get(element.value)
            // Intersect constraints, independent of order: select+text needs string,
            // date+text needs a numeric timestamp, and plural+text still needs number.
            const allowed = previous ? argumentTypes[previous].filter(type => argumentTypes[kind].includes(type)) : argumentTypes[kind]
            if (!allowed.length) throw new Error(`Incompatible argument ${element.value}: ${previous}/${kind}`)
            const combined = Object.keys(argumentTypes).find(name => argumentTypes[name].length === allowed.length
                && argumentTypes[name].every(type => allowed.includes(type)))
            output.set(element.value, combined)
        }
        if (element.options) for (const option of Object.values(element.options)) messageArguments(option.value, output)
        if (element.children) messageArguments(element.children, output)
    }
    return output
}

export function generateContracts(root = localeRoot) {
    const policy = JSON.parse(fs.readFileSync(path.join(root, "message-policy.json"), "utf8"))
    const literals = new Set(policy.literalKeys)
    const messages = new Map()
    function flatten(value, prefix = "") {
        for (const [name, child] of Object.entries(value)) {
            const key = prefix ? `${prefix}.${name}` : name
            if (typeof child === "string") {
                if (messages.has(key)) throw new Error(`Catalog collision: ${key}`)
                messages.set(key, child)
            } else if (child && typeof child === "object" && !Array.isArray(child)) flatten(child, key)
            else throw new Error(`Invalid translation: ${key}`)
        }
    }
    function visit(directory) {
        for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, "en"))) {
            const file = path.join(directory, entry.name)
            if (entry.isDirectory()) visit(file)
            else if (entry.name.endsWith(".json")) flatten(JSON.parse(fs.readFileSync(file, "utf8")))
        }
    }
    visit(path.join(root, "en"))
    for (const key of literals) if (!messages.has(key)) throw new Error(`Unknown literal policy key: ${key}`)
    const types = { number: "number", date: "Date | number", select: "string | boolean", text: "string | number", string: "string" }
    const lines = ["// Generated by npm run i18n:generate. Do not edit manually.", "export interface MessageParams {"]
    for (const [key, text] of [...messages].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
        if (literals.has(key)) continue
        const args = messageArguments(new IntlMessageFormat(text, "en").getAst())
        if (args.size) lines.push(`    ${JSON.stringify(key)}: { ${[...args].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([name, kind]) => `${JSON.stringify(name)}: ${types[kind]}`).join("; ")} }`)
    }
    lines.push("}", "")
    return lines.join("\n")
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        if (process.argv.slice(2).some(arg => !["--check", "--write"].includes(arg)) || process.argv.length !== 3) throw new Error("Use --check or --write")
        const output = generateContracts()
        const target = path.join(localeRoot, "message-params.generated.ts")
        if (process.argv[2] === "--write") fs.writeFileSync(target, output)
        else if (!fs.existsSync(target) || normalizeContractSource(fs.readFileSync(target, "utf8")) !== output) throw new Error("Stale message contracts. Run npm run i18n:generate and review the diff.")
        console.log("OK: ICU message contracts")
    } catch (error) { console.error(error.message); process.exitCode = 1 }
}
