import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { parseExpression } from "@babel/parser"

const defaultRoot = fileURLToPath(new URL("../..", import.meta.url))
const codePattern = /^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/

// Tooling only: Electron never imports files from the frontend at runtime.
/** @returns {Record<string, { name: string, intlLocale: string, htmlLang: string }>} */
export function readLocaleRegistry(root = defaultRoot) {
    const file = path.join(root, "seanime-web/src/locales/registry.json")
    const raw = fs.readFileSync(file, "utf8")
    const ast = parseExpression(raw)
    function checkDuplicates(node) {
        if (node.type !== "ObjectExpression") return
        const seen = new Set()
        for (const property of node.properties) {
            const key = property.key?.value ?? property.key?.name
            if (seen.has(key)) throw new Error(`Locale registry: duplicate key ${key}`)
            seen.add(key)
            if (property.value) checkDuplicates(property.value)
        }
    }
    checkDuplicates(ast)
    const registry = JSON.parse(raw)
    if (!registry || typeof registry !== "object" || Array.isArray(registry)) throw new Error("Invalid locale registry")
    for (const required of ["en", "es"]) {
        if (!Object.hasOwn(registry, required)) throw new Error(`Locale registry requires fallback ${required}`)
    }
    for (const [code, metadata] of Object.entries(registry)) {
        if (!codePattern.test(code)) throw new Error(`Invalid locale code: ${code}`)
        if (!metadata || typeof metadata !== "object" || Array.isArray(metadata)
            || JSON.stringify(Object.keys(metadata).sort()) !== JSON.stringify(["htmlLang", "intlLocale", "name"])
            || Object.values(metadata).some(value => typeof value !== "string" || !value.trim() || value !== value.trim())) {
            throw new Error(`Invalid locale metadata: ${code}`)
        }
        for (const tag of [code, metadata.intlLocale, metadata.htmlLang]) {
            if (Intl.getCanonicalLocales(tag)[0] !== tag) throw new Error(`Non-canonical locale tag: ${tag}`)
        }
        if (new Intl.Locale(metadata.intlLocale).language !== new Intl.Locale(code).language
            || new Intl.Locale(metadata.htmlLang).language !== new Intl.Locale(code).language) {
            throw new Error(`Locale language mismatch: ${code}`)
        }
        for (const formatter of [Intl.NumberFormat, Intl.DateTimeFormat, Intl.PluralRules]) {
            if (!formatter.supportedLocalesOf(metadata.intlLocale).length) throw new Error(`Unsupported Intl locale: ${metadata.intlLocale}`)
        }
    }
    return registry
}

export function generateNativeLocaleRegistry(root = defaultRoot) {
    const languages = Object.keys(readLocaleRegistry(root)).sort()
    return [
        "// Generated by npm run i18n:generate in seanime-web. Do not edit manually.",
        "// Standalone input for the native compiler; no frontend runtime dependency.",
        `export const denshiLocales = ${JSON.stringify(languages)} as const`,
        "export type DenshiLocale = (typeof denshiLocales)[number]",
        "",
    ].join("\n")
}

export function checkNativeLocaleRegistry(root = defaultRoot) {
    const file = path.join(root, "seanime-denshi/src/main/locale-registry.generated.ts")
    const expected = generateNativeLocaleRegistry(root)
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== expected) {
        throw new Error("Stale native locale registry. Run npm run i18n:generate in seanime-web and review the diff.")
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        if (process.argv.length !== 3 || !["--check", "--write"].includes(process.argv[2])) throw new Error("Use --check or --write")
        if (process.argv[2] === "--write") {
            fs.writeFileSync(path.join(defaultRoot, "seanime-denshi/src/main/locale-registry.generated.ts"), generateNativeLocaleRegistry())
        } else checkNativeLocaleRegistry()
        console.log("OK: locale registry and standalone native registration")
    } catch (error) { console.error(error.message); process.exitCode = 1 }
}
